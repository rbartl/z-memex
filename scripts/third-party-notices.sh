#!/usr/bin/env bash
# Regenerates THIRD_PARTY_NOTICES from the Go module cache and node_modules.
# Run from the repo root after changing go.mod or the vendored JS:
#   npm ci && scripts/third-party-notices.sh
set -euo pipefail

out=THIRD_PARTY_NOTICES
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT

# Packages whose code ends up in web/static/vendor (see "build" in package.json).
# d3.min.js bundles every d3-* module plus these three non-d3 dependencies.
js_pkgs="alpinejs htmx.org marked dompurify d3 $(cd node_modules && ls -d d3-*) delaunator internmap robust-predicates"

# Prints the license (and NOTICE) files in dir $1, or the override for $2.
license_text() {
  local dir=$1 name=$2 found=
  for f in "$dir"/*; do
    case "$(basename "$f" | tr '[:upper:]' '[:lower:]')" in
      licen[cs]e* | copying* | unlicense* | notice*) cat "$f"; echo; found=1 ;;
    esac
  done
  if [ -z "$found" ]; then
    # Some packages publish without their license file; keep a copy here.
    cat "scripts/licenses/${name%@*}" || { echo "no license found for $name" >&2; exit 1; }
  fi
}

# Groups packages with identical license text so each text is printed once.
add() {
  local name=$1 dir=$2 key
  license_text "$dir" "$name" > "$tmp/text"
  key=$(shasum -a 256 "$tmp/text" | cut -c1-16)
  [ -f "$tmp/$key.text" ] || mv "$tmp/text" "$tmp/$key.text"
  echo "$name" >> "$tmp/$key.names"
  grep -qx "$key" "$tmp/order" 2>/dev/null || echo "$key" >> "$tmp/order"
}

flush() {
  while read -r key; do
    echo "--------------------------------------------------------------------------------"
    sed 's/^/  /' "$tmp/$key.names"
    echo
    cat "$tmp/$key.text"
  done < "$tmp/order"
  rm -f "$tmp"/*.names "$tmp"/*.text "$tmp/order"
}

{
  echo "Third-party notices for memex"
  echo
  echo "memex is licensed under the Apache License 2.0 (see LICENSE). It includes"
  echo "the third-party software listed below, under the licenses that follow."
  echo "DOMPurify is dual-licensed; memex uses it under the Apache License 2.0."
  echo "This file is generated by scripts/third-party-notices.sh."
  echo
  echo "================================================================================"
  echo "JavaScript bundled in web/static/vendor"
  echo "================================================================================"
  for p in $js_pkgs; do
    add "$p@$(node -p "require('./node_modules/$p/package.json').version")" "node_modules/$p"
  done
  flush
  echo
  echo "================================================================================"
  echo "Go modules compiled into the memex binaries"
  echo "================================================================================"
  GOOS=linux go list -deps -f '{{with .Module}}{{.Path}}@{{.Version}} {{.Dir}}{{end}}' ./cmd/... |
    sort -u | grep -v '^gitlab.com/zollneritsch/' > "$tmp/mods"
  while read -r mod dir; do add "$mod" "$dir"; done < "$tmp/mods"
  flush
} > "$out"

echo "wrote $out"
